const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { identity, unique } = require('../question-dedup.js');
const root = path.resolve(__dirname, '..');
const load = name => JSON.parse(fs.readFileSync(path.join(root, 'data', name), 'utf8'));
const all = ['bank.json'].flatMap(name => load(name).questions);
const mockIds = new Set(['mocks.json'].flatMap(name => load(name).sets.filter(s => s.questionIds).flatMap(s => s.questionIds)));
const filtered = unique(all, mockIds);
assert.equal(new Set(filtered.map(identity)).size, filtered.length);
assert.deepEqual(unique(filtered, mockIds), filtered, 'Filtering is idempotent');
const retained = new Set(filtered.map(q => q.id));
for (const id of mockIds) assert(retained.has(id), `Published exam question removed: ${id}`);
const a = { id: 'a', type: 'mcq', prompt: 'Một câu hỏi? (Tình huống 1)' };
const b = { ...a, id: 'b', prompt: 'Một câu hỏi? (Tình huống 2)' };
assert.equal(unique([a, b]).length, 1);
assert.equal(unique([a, b], new Set(['b']))[0].id, 'b');
assert.equal(unique([a, {...b, prompt: 'Một câu hỏi khác?'}]).length, 2);
assert.equal(unique([a, {...b, type: 'code'}]).length, 2);
assert.equal(all.length - filtered.length, 563);
console.log(`Dedup: PASS (${all.length} → ${filtered.length}; ${all.length-filtered.length} duplicate entries hidden; all published exams preserved).`);
